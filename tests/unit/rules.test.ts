import { describe, expect, it } from "vitest";
import {
  analyzeFiles,
  binaryFiles,
  generatedOutput,
  irrelevantDirectories,
  largeFiles,
  largeFileThreshold,
  logDumpFiles,
  secretRiskFiles,
  shouldSkipContent,
} from "@/lib/analysis/file-rules";
import {
  analyzePrompt,
  duplicateInstructions,
  excessiveExamples,
  logDumpPrompt,
  missingSuccessCriteria,
  promptBoilerplate,
  secretRiskPrompt,
  vagueTask,
} from "@/lib/analysis/prompt-rules";
import { RULE_IDS, type ScannedFile } from "@/lib/analysis/types";

const file = (path: string, tokens = 100, content?: string): ScannedFile => ({
  path,
  size: tokens * 4,
  tokens,
  content,
});
const ctx = (prompt = "Fix the session timeout in src/auth/session.ts", tokenBudget = 20_000) => ({
  prompt,
  tokenBudget,
});
const GOOD_PROMPT =
  "In `src/auth/session.ts`, the `refreshSession` function drops the user after 15 minutes. " +
  "It should keep the session alive while the tab is active, and `npm test` must pass.";

describe("large-file", () => {
  it("scales the threshold with the budget within fixed bounds", () => {
    expect(largeFileThreshold(5_000)).toBe(2_000);
    expect(largeFileThreshold(20_000)).toBe(4_000);
    expect(largeFileThreshold(500_000)).toBe(10_000);
  });

  it("flags files above the threshold and recommends excluding them", () => {
    const result = largeFiles([file("src/big.ts", 12_000), file("src/small.ts", 300)], ctx());
    expect(result.findings).toHaveLength(1);
    expect(result.findings[0]).toMatchObject({
      ruleId: "large-file",
      severity: "high",
      filePath: "src/big.ts",
      estimatedTokensSaved: 12_000,
    });
    expect(result.verdicts.has("src/big.ts")).toBe(true);
    expect(result.verdicts.has("src/small.ts")).toBe(false);
  });

  it("keeps a large file the task names, but still warns", () => {
    const result = largeFiles([file("src/auth/session.ts", 6_000)], ctx());
    expect(result.findings[0]).toMatchObject({ severity: "low", estimatedTokensSaved: 0 });
    expect(result.verdicts.size).toBe(0);
  });
});

describe("generated-output", () => {
  it("groups build and dependency directories into one finding each", () => {
    const result = generatedOutput(
      [file("dist/a.js", 500), file("dist/b.js", 700), file("web/node_modules/x/index.js", 900), file("src/a.ts")],
      ctx(),
    );
    expect(result.findings.map((finding) => finding.filePath).sort()).toEqual(["dist/", "web/node_modules/"]);
    expect(result.findings.find((finding) => finding.filePath === "dist/")?.estimatedTokensSaved).toBe(1200);
    expect(result.verdicts.get("dist/a.js")?.exclusion).toBe("dist/");
    expect(result.verdicts.has("src/a.ts")).toBe(false);
  });

  it("flags lockfiles, minified bundles and generated headers", () => {
    const result = generatedOutput(
      [
        file("package-lock.json", 9000),
        file("public/app.min.js", 4000),
        file("src/api/client.ts", 800, "// Code generated by openapi-gen. DO NOT EDIT.\nexport {}"),
        file("src/api/handwritten.ts", 800, "export const a = 1;"),
      ],
      ctx(),
    );
    expect(result.findings.map((finding) => finding.filePath).sort()).toEqual([
      "package-lock.json",
      "public/app.min.js",
      "src/api/client.ts",
    ]);
  });
});

describe("binary-file", () => {
  it("flags binary extensions and files containing NUL bytes", () => {
    const result = binaryFiles(
      [file("logo.png", 3000), file("data/blob", 200, "\u0000"), file("src/a.ts", 100, "export {}")],
      ctx(),
    );
    expect(result.findings.map((finding) => finding.filePath).sort()).toEqual(["data/blob", "logo.png"]);
    expect(result.findings.every((finding) => finding.ruleId === "binary-file")).toBe(true);
  });

  it("groups many binaries in one directory", () => {
    const result = binaryFiles([file("img/a.png"), file("img/b.png"), file("img/c.png")], ctx());
    expect(result.findings).toHaveLength(1);
    expect(result.findings[0].filePath).toBe("img/*.png");
    expect(result.findings[0].estimatedTokensSaved).toBe(300);
  });
});

describe("log-dump", () => {
  it("flags log files, log directories and log-like content", () => {
    const logContent = Array.from({ length: 30 }, (_, i) => `2026-01-01 10:00:${String(i).padStart(2, "0")} INFO request ${i}`).join("\n");
    const result = logDumpFiles(
      [file("debug.log", 5000), file("logs/app/out.txt", 800), file("notes/run.txt", 900, logContent), file("src/logger.ts", 200, "export const log = console.log;")],
      ctx(),
    );
    expect(result.findings.map((finding) => finding.filePath).sort()).toEqual(["debug.log", "logs/", "notes/run.txt"]);
  });

  it("flags a long log paste in the prompt and estimates the excess", () => {
    const paste = Array.from({ length: 40 }, (_, i) => `[ERROR] 12:00:${String(i).padStart(2, "0")} worker ${i} crashed`).join("\n");
    const [finding] = logDumpPrompt(`The worker crashes:\n${paste}`);
    expect(finding).toMatchObject({ ruleId: "log-dump", filePath: null });
    expect(finding.estimatedTokensSaved).toBeGreaterThan(0);
    expect(logDumpPrompt("TypeError: x is undefined\n    at foo (src/a.ts:1:2)")).toEqual([]);
  });
});

describe("duplicate-instruction", () => {
  it("flags instructions repeated within the prompt", () => {
    const prompt = "Add pagination to the users list.\n- Do not change the public API of the service.\nUse cursor pagination.\n- do not change the public API of the service";
    const findings = duplicateInstructions(prompt);
    expect(findings).toHaveLength(1);
    expect(findings[0]).toMatchObject({ ruleId: "duplicate-instruction", filePath: null });
    expect(findings[0].estimatedTokensSaved).toBeGreaterThan(0);
  });

  it("flags instructions that restate CLAUDE.md", () => {
    const claudeMd = "# Project\n- Always run the linter before committing changes.\n";
    const findings = duplicateInstructions("Add pagination.\nAlways run the linter before committing changes.", claudeMd);
    expect(findings).toHaveLength(1);
    expect(findings[0].filePath).toBe("CLAUDE.md");
  });

  it("ignores short lines and repeated lines inside code blocks", () => {
    const prompt = "Fix it.\nFix it.\n```\nconst value = computeSomethingExpensive();\nconst value = computeSomethingExpensive();\n```";
    expect(duplicateInstructions(prompt)).toEqual([]);
  });
});

describe("missing-success-criteria", () => {
  it("flags prompts with no checkable outcome", () => {
    const [finding] = missingSuccessCriteria("Refactor the billing module in src/billing to use the new client.");
    expect(finding.ruleId).toBe("missing-success-criteria");
  });

  it.each([
    "Refactor billing. Acceptance criteria: invoices render the same.",
    "The endpoint should return 404 for unknown ids.",
    "Update the parser so that empty lines are skipped.",
    "Fix the flaky test.\n- [ ] CI is green",
    "Rename the helper; all tests must pass.",
  ])("accepts %j", (prompt) => {
    expect(missingSuccessCriteria(prompt)).toEqual([]);
  });
});

describe("vague-task", () => {
  it.each(["fix the bug", "Make it better and clean up the code so that everything is nicer for everyone", "the app is broken somehow, please improve it and make it work again soon"])(
    "flags %j",
    (prompt) => {
      expect(vagueTask(prompt)[0]?.ruleId).toBe("vague-task");
    },
  );

  it("marks very short prompts as high severity", () => {
    expect(vagueTask("fix login")[0].severity).toBe("high");
  });

  it("accepts a specific task", () => {
    expect(vagueTask(GOOD_PROMPT)).toEqual([]);
  });
});

describe("excessive-examples", () => {
  const block = (i: number) => "```ts\nconst example" + i + " = { id: " + i + ", name: 'x' };\n```";

  it("flags prompts with many code blocks and counts the surplus", () => {
    const prompt = `Convert these:\n${[1, 2, 3, 4, 5].map(block).join("\n")}`;
    const [finding] = excessiveExamples(prompt);
    expect(finding.ruleId).toBe("excessive-examples");
    expect(finding.estimatedTokensSaved).toBeGreaterThan(0);
  });

  it("flags many inline examples", () => {
    const prompt = "Handle dates, e.g. ISO. For example 2024-01-01. For instance epoch. Such as RFC 2822, e.g. Tue.";
    expect(excessiveExamples(prompt)).toHaveLength(1);
  });

  it("accepts one or two examples", () => {
    expect(excessiveExamples(`Convert like this:\n${block(1)}\n${block(2)}`)).toEqual([]);
  });
});

describe("secret-risk", () => {
  it("flags secret files without needing their content", () => {
    const result = secretRiskFiles([file(".env", 50), file("config/credentials.json", 80), file("src/a.ts", 100, "export {}")]);
    expect(result.findings.map((finding) => finding.filePath).sort()).toEqual([".env", "config/credentials.json"]);
    expect(result.findings.every((finding) => finding.severity === "high")).toBe(true);
    expect(result.verdicts.has(".env")).toBe(true);
  });

  it("flags credentials inside ordinary files without echoing them", () => {
    const secret = "AKIAIOSFODNN7EXAMPLE";
    const result = secretRiskFiles([file("src/aws.ts", 100, `const id = "${secret}";`)]);
    expect(result.findings).toHaveLength(1);
    expect(JSON.stringify(result.findings)).not.toContain(secret);
  });

  it("flags credentials pasted into the prompt without echoing them", () => {
    const secret = `ghp_${"z".repeat(36)}`;
    const findings = secretRiskPrompt(`Use token ${secret} to call the API`);
    expect(findings).toHaveLength(1);
    expect(JSON.stringify(findings)).not.toContain(secret);
    expect(secretRiskPrompt(GOOD_PROMPT)).toEqual([]);
  });

  it("never allows content downloads for secret, binary, generated or log paths", () => {
    for (const path of [".env.local", "id_rsa", "a.png", "dist/x.js", "yarn.lock", "debug.log"]) {
      expect(shouldSkipContent(path)).toBe(true);
    }
    expect(shouldSkipContent("src/index.ts")).toBe(false);
  });
});

describe("irrelevant-directory", () => {
  const files = [file("docs/guide.md", 2000), file("docs/api.md", 1000), file(".github/workflows/ci.yml", 300), file("src/auth/session.ts", 400)];

  it("groups unrelated supporting directories", () => {
    const result = irrelevantDirectories(files, ctx());
    expect(result.findings.map((finding) => finding.filePath).sort()).toEqual([".github/", "docs/"]);
    expect(result.findings.find((finding) => finding.filePath === "docs/")?.estimatedTokensSaved).toBe(3000);
    expect(result.verdicts.has("src/auth/session.ts")).toBe(false);
  });

  it("keeps a directory the task is about", () => {
    const result = irrelevantDirectories(files, ctx("Update the docs to describe the new session timeout"));
    expect(result.findings.map((finding) => finding.filePath)).toEqual([".github/"]);
  });
});

describe("prompt-boilerplate", () => {
  it("flags greetings, role-play and politeness filler", () => {
    const prompt = "Hello Claude!\nYou are an expert TypeScript engineer.\nCould you please rename `getUser` to `fetchUser` in src/api.ts?\nThanks in advance!";
    const [finding] = promptBoilerplate(prompt);
    expect(finding.ruleId).toBe("prompt-boilerplate");
    expect(finding.estimatedTokensSaved).toBeGreaterThan(5);
  });

  it("accepts a direct prompt", () => {
    expect(promptBoilerplate(GOOD_PROMPT)).toEqual([]);
  });
});

describe("rule orchestration", () => {
  it("attributes each file to a single rule so savings are not double-counted", () => {
    const files = [file("docs/dist/huge.png", 9000), file("dist/.env", 50), file("src/a.ts", 100)];
    const result = analyzeFiles(files, ctx());
    expect(result.verdicts.get("docs/dist/huge.png")?.ruleId).toBe("binary-file");
    expect(result.verdicts.get("dist/.env")?.ruleId).toBe("secret-risk");
    const total = result.findings.reduce((sum, finding) => sum + finding.estimatedTokensSaved, 0);
    expect(total).toBe(9050);
  });

  it("returns no findings for a clean prompt", () => {
    expect(analyzePrompt(GOOD_PROMPT, GOOD_PROMPT)).toEqual([]);
  });

  it("covers every rule in the specification", () => {
    expect([...RULE_IDS].sort()).toEqual(
      [
        "binary-file",
        "duplicate-instruction",
        "excessive-examples",
        "generated-output",
        "irrelevant-directory",
        "large-file",
        "log-dump",
        "missing-success-criteria",
        "prompt-boilerplate",
        "secret-risk",
        "vague-task",
      ].sort(),
    );
  });
});
