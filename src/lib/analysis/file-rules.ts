function extension(path: string): string {
  const base = path.slice(path.lastIndexOf("/") + 1);
  const dot = base.lastIndexOf(".");
  return dot > 0 ? base.slice(dot + 1).toLowerCase() : "";
}

const basename = (path: string) => path.slice(path.lastIndexOf("/") + 1);

/** Returns the path prefix up to the first segment found in `dirs` ("a/dist/"), if any. */
function matchedDir(path: string, dirs: Set<string>): string | null {
  const segments = path.split("/");
  for (let i = 0; i < segments.length - 1; i++) {
    if (dirs.has(segments[i].toLowerCase())) return `${segments.slice(0, i + 1).join("/")}/`;
  }
  return null;
}

export function isBinaryPath(path: string): boolean {
  return BINARY_EXTENSIONS.has(extension(path));
}

export function isGeneratedPath(path: string): boolean {
  return (
    matchedDir(path, GENERATED_DIRS) !== null ||
    GENERATED_FILES.some((re) => re.test(basename(path)))
  );
}

export function isLogPath(path: string): boolean {
  return matchedDir(path, LOG_DIRS) !== null || LOG_FILES.some((re) => re.test(basename(path)));
}

/** True when a file's content should never be downloaded. */
export function shouldSkipContent(path: string): boolean {
  return isSecretPath(path) || isBinaryPath(path) || isGeneratedPath(path) || isLogPath(path);
}

/** True when the prompt names this file (full path, or a distinctive basename). */
export function isMentioned(path: string, prompt: string): boolean {
  if (prompt.includes(path)) return true;
  const base = basename(path);
  return base.length >= 5 && base.includes(".") && new RegExp(`(^|[^\\w.-])${escapeRegExp(base)}($|[^\\w-])`).test(prompt);
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

interface Hit {
  file: ScannedFile;
  /** Directory group ("dist/") or null when the file is flagged on its own. */
  dir: string | null;
}

/**
 * Turns per-file hits into findings: files under the same flagged directory
 * collapse into one finding so a committed `node_modules/` is one line, not 10,000.
 */
function summarize(
  ruleId: RuleId,
  hits: Hit[],
  describe: (target: string, count: number, isDir: boolean) => { explanation: string; suggestedAction: string; reason: string },
  severityFor: (tokens: number) => Severity,
): FileRuleResult {
  const groups = new Map<string, { isDir: boolean; files: ScannedFile[] }>();
  for (const { file, dir } of hits) {
    const key = dir ?? file.path;
    const group = groups.get(key) ?? { isDir: dir !== null, files: [] };
    group.files.push(file);
    groups.set(key, group);
  }
  const findings: Finding[] = [];
  const verdicts = new Map<string, FileVerdict>();
  for (const [target, group] of groups) {
    const tokens = group.files.reduce((sum, file) => sum + file.tokens, 0);
    const text = describe(target, group.files.length, group.isDir);
    findings.push({
      ruleId,
      severity: severityFor(tokens),
      filePath: target,
      explanation: text.explanation,
      suggestedAction: text.suggestedAction,
      estimatedTokensSaved: tokens,
    });
    for (const file of group.files) {
      verdicts.set(file.path, { ruleId, reason: text.reason, exclusion: target });
    }
  }
  return { findings, verdicts };
}

const bySize =
  (ctx: AnalysisContext, fallback: Severity = "low") =>
  (tokens: number): Severity =>
    tokens > ctx.tokenBudget * 0.25 ? "high" : tokens > ctx.tokenBudget * 0.05 ? "medium" : fallback;

const plural = (count: number) => (count === 1 ? "1 file" : `${count.toLocaleString("en-US")} files`);

/** Secret risk: secret-looking files (never read) and credentials inside readable files. */
export function secretRiskFiles(files: ScannedFile[]): FileRuleResult {
  const findings: Finding[] = [];
  const verdicts = new Map<string, FileVerdict>();
  for (const file of files) {
    if (isSecretPath(file.path)) {
      findings.push({
        ruleId: "secret-risk",
        severity: "high",
        filePath: file.path,
        explanation: "This looks like a secrets file. ContextBudget did not read it and it is never included in a pack.",
        suggestedAction: "Keep it out of Claude Code's context, and consider removing it from the repository.",
        estimatedTokensSaved: file.tokens,
      });
      verdicts.set(file.path, { ruleId: "secret-risk", reason: "Secrets file (never read)", exclusion: file.path });
      continue;
    }
    if (!file.content) continue;
    const kinds = [...new Set(findSecrets(file.content).map((match) => match.kind))];
    if (kinds.length === 0) continue;
    findings.push({
      ruleId: "secret-risk",
      severity: "high",
      filePath: file.path,
      explanation: `Possible credentials found in this file (${kinds.join(", ")}).`,
      suggestedAction: "Exclude the file from context and rotate the credential if it is real.",
      estimatedTokensSaved: file.tokens,
    });
    verdicts.set(file.path, { ruleId: "secret-risk", reason: "Contains possible credentials", exclusion: file.path });
  }
  return { findings, verdicts };
}

export function binaryFiles(files: ScannedFile[], ctx: AnalysisContext): FileRuleResult {
  const hits: Hit[] = files
    .filter((file) => isBinaryPath(file.path) || file.content?.includes("\u0000"))
    .map((file) => ({ file, dir: null }));
  // Group binaries by their parent directory when several sit together.
  const perDir = new Map<string, number>();
  for (const { file } of hits) {
    const dir = file.path.includes("/") ? `${file.path.slice(0, file.path.lastIndexOf("/"))}/` : "";
    perDir.set(dir, (perDir.get(dir) ?? 0) + 1);
  }
  for (const hit of hits) {
    const dir = hit.file.path.includes("/") ? `${hit.file.path.slice(0, hit.file.path.lastIndexOf("/"))}/` : "";
    if (dir && (perDir.get(dir) ?? 0) >= 3) hit.dir = `${dir}*.${extension(hit.file.path) || "bin"}`;
  }
  return summarize(
    "binary-file",
    hits,
    (target, count, grouped) => ({
      explanation: grouped
        ? `${plural(count)} matching ${target} are binary. Claude Code cannot use them as text context.`
        : "Binary file. Claude Code cannot use it as text context.",
      suggestedAction: "Exclude binary files; describe the asset in a sentence if it matters.",
      reason: "Binary file",
    }),
    bySize(ctx),
  );
}

export function generatedOutput(files: ScannedFile[], ctx: AnalysisContext): FileRuleResult {
  const hits: Hit[] = [];
  for (const file of files) {
    const dir = matchedDir(file.path, GENERATED_DIRS);
    if (dir) hits.push({ file, dir });
    else if (
      GENERATED_FILES.some((re) => re.test(basename(file.path))) ||
      (file.content !== undefined && GENERATED_HEADER.test(file.content.slice(0, 600)))
    ) {
      hits.push({ file, dir: null });
    }
  }
  return summarize(
    "generated-output",
    hits,
    (target, count, isDir) => ({
      explanation: isDir
        ? `${target} holds build or dependency output (${plural(count)}). It is derived from other files and adds no information.`
        : "Generated file (lockfile, bundle, or marked as auto-generated). It is derived from other files.",
      suggestedAction: isDir
        ? `Exclude ${target} and add it to .contextbudgetignore.`
        : "Exclude it; point Claude Code at the source it is generated from instead.",
      reason: "Generated output",
    }),
    bySize(ctx, "medium"),
  );
}

export function logDumpFiles(files: ScannedFile[], ctx: AnalysisContext): FileRuleResult {
  const hits: Hit[] = [];
  for (const file of files) {
    const dir = matchedDir(file.path, LOG_DIRS);
    if (dir) {
      hits.push({ file, dir });
    } else if (LOG_FILES.some((re) => re.test(basename(file.path)))) {
      hits.push({ file, dir: null });
    } else if (file.content) {
      const lines = file.content.split("\n").filter((line) => line.trim());
      if (lines.length >= 20 && lines.filter((line) => LOG_LINE.test(line)).length / lines.length > 0.6) {
        hits.push({ file, dir: null });
      }
    }
  }
  return summarize(
    "log-dump",
    hits,
    (target, count, isDir) => ({
      explanation: isDir
        ? `${target} contains log output (${plural(count)}). Logs are long, repetitive and mostly noise.`
        : "Log output. Logs are long, repetitive and mostly noise.",
      suggestedAction: "Exclude it and paste only the few lines around the error into your prompt.",
      reason: "Log dump",
    }),
    bySize(ctx, "medium"),
  );
}

export function irrelevantDirectories(files: ScannedFile[], ctx: AnalysisContext): FileRuleResult {
  const keywords = extractKeywords(ctx.prompt);
  const mentionedDirs = new Map<string, boolean>();
  const isRelevant = (dir: string) => {
    const cached = mentionedDirs.get(dir);
    if (cached !== undefined) return cached;
    const name = dir.replace(/\/$/, "");
    const leaf = name.slice(name.lastIndexOf("/") + 1);
    const words = splitWords(leaf);
    const relevant =
      ctx.prompt.includes(name + "/") ||
      words.some((word) => keywords.has(word) || keywords.has(word.replace(/s$/, "")) || keywords.has(`${word}s`));
    mentionedDirs.set(dir, relevant);
    return relevant;
  };
  const hits: Hit[] = [];
  for (const file of files) {
    const dir = matchedDir(file.path, IRRELEVANT_DIRS);
    if (dir && !isRelevant(dir) && !isMentioned(file.path, ctx.prompt)) hits.push({ file, dir });
  }
  return summarize(
    "irrelevant-directory",
    hits,
    (target, count) => ({
      explanation: `${target} (${plural(count)}) is supporting material your task does not mention.`,
      suggestedAction: `Exclude ${target} unless the task is about it.`,
      reason: "Directory not related to the task",
    }),
    bySize(ctx),
  );
}

export function largeFileThreshold(tokenBudget: number): number {
  return Math.min(10_000, Math.max(2_000, Math.round(tokenBudget * 0.2)));
}

export function largeFiles(files: ScannedFile[], ctx: AnalysisContext): FileRuleResult {
  const threshold = largeFileThreshold(ctx.tokenBudget);
  const findings: Finding[] = [];
  const verdicts = new Map<string, FileVerdict>();
  for (const file of files) {
    if (file.tokens <= threshold) continue;
    const share = Math.round((file.tokens / ctx.tokenBudget) * 100);
    const mentioned = isMentioned(file.path, ctx.prompt);
    findings.push({
      ruleId: "large-file",
      severity: mentioned ? "low" : file.tokens > ctx.tokenBudget * 0.5 ? "high" : "medium",
      filePath: file.path,
      explanation: `About ${file.tokens.toLocaleString("en-US")} tokens — ${share}% of your budget in a single file.`,
      suggestedAction: mentioned
        ? "Your task names this file, so it stays. Tell Claude Code which function or line range to read."
        : "Exclude it, or name the specific function or line range Claude Code should read.",
      estimatedTokensSaved: mentioned ? 0 : file.tokens,
    });
    if (!mentioned) {
      verdicts.set(file.path, { ruleId: "large-file", reason: "Large file", exclusion: file.path });
    }
  }
  return { findings, verdicts };
}

/**
 * Runs every file rule. A file is attributed to the first rule that flags it
 * (most serious first) so token savings are never double-counted.
 */
export function analyzeFiles(files: ScannedFile[], ctx: AnalysisContext): FileRuleResult {
  const rules: ((files: ScannedFile[], ctx: AnalysisContext) => FileRuleResult)[] = [
    secretRiskFiles,
    binaryFiles,
    generatedOutput,
    logDumpFiles,
    irrelevantDirectories,
    largeFiles,
  ];
  const findings: Finding[] = [];
  const verdicts = new Map<string, FileVerdict>();
  let remaining = files;
  for (const rule of rules) {
    const result = rule(remaining, ctx);
    findings.push(...result.findings);
    for (const [path, verdict] of result.verdicts) verdicts.set(path, verdict);
    remaining = remaining.filter((file) => !result.verdicts.has(file.path));
  }
  return { findings, verdicts };
}
